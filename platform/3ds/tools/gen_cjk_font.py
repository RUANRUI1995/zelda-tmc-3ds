#!/usr/bin/env python3
"""Build the bottom screen's 12x12 CJK glyph table from Ark Pixel 12px.

The port's own UI (bottom screen, updater) is drawn with a 5x7 bitmap font
that covers Latin-1 only. Chinese needs a real pixel font: a 12px outline
font scaled down smears, and Microsoft's fonts may not be redistributed.
Ark Pixel 12px is a hand-drawn pixel font under SIL OFL 1.1, so its glyphs
can be embedded.

  input   Ark Pixel 12px proportional zh_Hans, BDF form
          https://github.com/TakWolf/ark-pixel-font/releases
  charset the ASCII range plus every non-ASCII character the Chinese column
          of port/port_text_i18n.c uses, so the table holds only what the
          UI can actually draw
  output  a sorted (code point, advance, 12x12 1bpp rows) table

Every glyph is placed in one 12-row cell on a shared baseline, so a line of
mixed ASCII and Chinese lines up the way the game's own font does. Run it
again after adding UI strings:

  python3 platform/3ds/tools/gen_cjk_font.py \
      --bdf ark-pixel-12px-proportional-zh_hans.bdf
"""
import argparse
import re
import sys

CELL_W = 12
CELL_H = 12
# The cell's baseline sits on row 10, which puts an 11-row Chinese glyph at
# rows 0..10 and a 9-row capital at rows 1..9: the proportions the font was
# drawn for.
BASELINE_ROW = 10


def parse_bdf(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    glyphs = {}
    for block in text.split("STARTCHAR")[1:]:
        enc = re.search(r"ENCODING\s+(-?\d+)", block)
        bbx = re.search(r"BBX\s+(\d+)\s+(\d+)\s+(-?\d+)\s+(-?\d+)", block)
        dw = re.search(r"DWIDTH\s+(-?\d+)", block)
        bm = re.search(r"BITMAP\n(.*?)\nENDCHAR", block, re.S)
        if not (enc and bbx and dw and bm):
            continue
        cp = int(enc.group(1))
        w, h, xoff, yoff = map(int, bbx.groups())
        rows = [l.strip() for l in bm.group(1).split("\n") if l.strip()]
        bits = []
        nibbles = len(rows[0]) * 4 if rows else 0
        for r in rows:
            v = int(r, 16)
            bits.append([(v >> (nibbles - 1 - i)) & 1 for i in range(nibbles)])
        glyphs[cp] = {"w": w, "h": h, "xoff": xoff, "yoff": yoff,
                      "adv": int(dw.group(1)), "bits": bits}
    return glyphs


def charset(i18n_path):
    src = open(i18n_path, encoding="utf-8").read()
    chars = {chr(c) for c in range(0x20, 0x7F)}
    for block in re.findall(r"\{([^{}]*)\},", src, re.S):
        strs = re.findall(r'"((?:[^"\\]|\\.)*)"', block)
        if len(strs) >= 6:
            chars |= {ch for ch in strs[5] if ord(ch) > 0x7F}
    return chars


def cell(g, cp):
    """The glyph in one CELL_H x CELL_W cell, or None if it does not fit."""
    top = BASELINE_ROW - g["yoff"] - g["h"]
    left = g["xoff"]
    if top < 0 or left < 0 or top + g["h"] > CELL_H or left + g["w"] > CELL_W:
        return None
    rows = []
    for y in range(CELL_H):
        value = 0
        gy = y - top
        if 0 <= gy < g["h"]:
            for x in range(g["w"]):
                if g["bits"][gy][x]:
                    value |= 1 << (CELL_W - 1 - (left + x))
        rows.append(value)
    return rows


def main():
    here = __file__.rsplit("/", 1)[0].rsplit("\\", 1)[0]
    ap = argparse.ArgumentParser()
    ap.add_argument("--bdf", required=True)
    ap.add_argument("--i18n", default=here + "/../../../port/port_text_i18n.c")
    ap.add_argument("--out", default=here + "/../source/ui_cjk_font.inc")
    args = ap.parse_args()

    glyphs = parse_bdf(args.bdf)
    chars = charset(args.i18n)
    entries, missing, clipped = [], [], []
    for ch in sorted(chars):
        cp = ord(ch)
        # A BDF carries no bitmap for the space: it is advance alone.
        if cp == 0x20:
            entries.append((cp, 6, [0] * CELL_H))
            continue
        g = glyphs.get(cp)
        if not g:
            missing.append(ch)
            continue
        rows = cell(g, cp)
        if rows is None:
            clipped.append(ch)
            continue
        entries.append((cp, g["adv"], rows))

    if missing:
        print("no glyph in the font: " + "".join(missing), file=sys.stderr)
    if clipped:
        print("glyph does not fit the 12x12 cell: " + "".join(clipped), file=sys.stderr)
    if missing or clipped:
        return 1

    out = []
    out.append("/* Generated by platform/3ds/tools/gen_cjk_font.py - do not edit.")
    out.append(" *")
    out.append(" * Glyphs: Ark Pixel 12px proportional zh_Hans")
    out.append(" * Copyright (c) 2021 TakWolf, https://github.com/TakWolf/ark-pixel-font")
    out.append(" * Licensed under the SIL Open Font License, Version 1.1 (see")
    out.append(" * THIRD-PARTY-LICENSES.md). Only the characters the Chinese UI uses")
    out.append(" * are included. */")
    out.append("")
    # UI_CJK_CELL_W / UI_CJK_CELL_H come from ui_font_3ds.h, which the
    # including translation unit has already seen.
    out.append("#define UI_CJK_BASELINE %d" % BASELINE_ROW)
    out.append("#define UI_CJK_ROW_BYTES 2")
    out.append("#define UI_CJK_GLYPH_COUNT %d" % len(entries))
    out.append("")
    out.append("typedef struct UiCjkGlyph {")
    out.append("    uint32_t codePoint;")
    out.append("    uint8_t advance;")
    out.append("    uint8_t rows[UI_CJK_CELL_H][UI_CJK_ROW_BYTES];")
    out.append("} UiCjkGlyph;")
    out.append("")
    out.append("static const UiCjkGlyph kUiCjkGlyphs[UI_CJK_GLYPH_COUNT] = {")
    for cp, adv, rows in entries:
        body = ",".join("{0x%02X,0x%02X}" % ((r >> 4) & 0xFF, (r & 0x0F) << 4) for r in rows)
        out.append("    { 0x%04X, %d, { %s } }," % (cp, adv, body))
    out.append("};")
    out.append("")

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("%d glyphs -> %s" % (len(entries), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
